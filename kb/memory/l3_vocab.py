# ── 三层合并后的合法场景词集合（供校验用）─────────────────
VALID_SCENE_KEYS: frozenset[str] = (
    frozenset(HYPERNYM_MAP.keys())          # ①实体
    | frozenset(HYPERNYM_MAP.values())      # ②上位
    | frozenset(SITUATION_MAP.values())     # ③情境
)


def expand_scene_words(entities: list[str]) -> list[str]:
    """把抽取到的实体词扩展为三层场景词（实体 + 上位 + 情境）。

    检索侧本地分解器的核心函数之一：写入侧与检索侧共用它，
    保证「咖啡」与「柠檬茶」都能扩出「饮品」，从而互相命中。

    角色名（专有名词）不在 HYPERNYM_MAP/SITUATION_MAP 中，会被原样保留 ——
    它们是倒排索引的合法居民（首府 P0-3 裁定）。
    """
    out: list[str] = []
    seen: set[str] = set()

    def _push(w: str) -> None:
        if w and w not in seen and w not in FORBIDDEN_KEYS:
            seen.add(w)
            out.append(w)

    for e in entities:
        _push(e)                                  # ①实体本身（含角色名）
        if e in HYPERNYM_MAP:
            _push(HYPERNYM_MAP[e])                # ②上位词
        if e in SITUATION_MAP:
            _push(SITUATION_MAP[e])               # ③情境词
    return out


def is_valid_scene_key(k: str) -> bool:
    return k in VALID_SCENE_KEYS and k not in FORBIDDEN_KEYS
