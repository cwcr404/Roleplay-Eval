def deep_roles() -> list[str]:
    """深档 8 人（有序）。"""
    return list(RELATIONS.keys())


def shallow_roles() -> list[str]:
    """浅档一行式认知。"""
    return list(ACQUAINTANCES.keys())


def all_known() -> list[str]:
    """芽衣认得的全部人（深 + 浅）。"""
    return deep_roles() + shallow_roles()


def relation_of(role: str) -> dict | None:
    """深档查表；浅档返回 None。"""
    return RELATIONS.get(role)


def acquaintance_of(role: str) -> dict | None:
    return ACQUAINTANCES.get(role)


def scene_of(name: str) -> dict | None:
    return SCENES.get(name)


def scenes_with(role: str) -> list[str]:
    """某个角色参与的场景（供前端双路信号：提到角色 → 亮她的场景）。"""
    return [n for n, s in SCENES.items() if role in s.get("characters", [])]


def audit() -> tuple[bool, list[str]]:
    """认知层验收：每条目必须挂出处；深档锚点 >=3。

    首府纪律：认知表是芽衣的**世界观金标集** —— 无出处的条目不进表。
    返回 (是否全绿, 问题清单)。
    """
    problems: list[str] = []
    for name, r in RELATIONS.items():
        if len(r.get("anchors", [])) < 3:
            problems.append(f"[深档] {name}: 锚点 {len(r.get('anchors', []))} < 3")
        if not r.get("sources"):
            problems.append(f"[深档] {name}: 无出处")
    for name, a in ACQUAINTANCES.items():
        if not a.get("sources"):
            problems.append(f"[浅档] {name}: 无出处")
    for name, s in SCENES.items():
        if not s.get("sources"):
            problems.append(f"[场景] {name}: 无出处")
    return (not problems), problems


